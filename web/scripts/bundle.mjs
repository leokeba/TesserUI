// After `vite build`: writes dist/index.html, the gzipped copies of ui.js
// and its chunks (zopfli, which any gzip decoder reads) and the C++ header
// the node serves them from (src/tesserui/bundle/tesserui_bundle.h, DESIGN.md
// §9.4), and enforces the budgets (§2): 65 KB for ui.js, what a page loads
// first, 71 KB with the widgets' chunk, what a node's flash holds (70 until
// the file browser, 2026-10-25); the file browser's and the editor's chunks
// have budgets of their own, 6 and 4 KB. `--check` only measures. A node
// without file browsers or the editor leaves their chunks out of its flash
// (TESSERUI_NO_FILES_UI, TESSERUI_NO_EDITOR: OPTIONAL below).

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { gzipAsync } from '@gfx/zopfli';

const BUDGET = 65 * 1024;
const TOTAL = 71 * 1024;
const OWN = { files: 6 * 1024, editor: 4 * 1024 };
// The chunks a firmware may leave out, and the macro (or Kconfig option,
// CONFIG_ before it) that does: WebUi then answers for them with a module
// that fails, which the page takes for a widget it can't draw (DESIGN.md §9.4).
const OPTIONAL = { files: 'TESSERUI_NO_FILES_UI', editor: 'TESSERUI_NO_EDITOR' };
const web = new URL('../', import.meta.url);
const dist = new URL('dist/', web);
const header = new URL('../src/tesserui/bundle/tesserui_bundle.h', web);
const { version } = JSON.parse(readFileSync(new URL('package.json', web), 'utf8'));

const zopfli = async (file) => Buffer.from(await gzipAsync(readFileSync(new URL(file, dist)), { numiterations: 15 }));
const js = readFileSync(new URL('ui.js', dist));
const gz = await zopfli('ui.js');
// ui/<widget>-<hash>.js, by name: the header's order follows the build.
const chunks = await Promise.all(
  readdirSync(new URL('ui/', dist))
    .filter((f) => f.endsWith('.js'))
    .sort()
    .map(async (name) => ({ name, gz: await zopfli(`ui/${name}`) })),
);
const own = (c) => OWN[c.name.replace(/-.*/, '')];
const shared = chunks.filter((c) => !own(c));
const total = gz.length + shared.reduce((n, c) => n + c.gz.length, 0);
console.log(`ui.js: ${js.length} bytes, ${gz.length} gzipped (budget ${BUDGET})`);
console.log(`with ${shared.map((c) => `ui/${c.name}`).join(', ')}: ${total} gzipped (budget ${TOTAL})`);
for (const c of chunks) console.log(`  ui/${c.name}: ${c.gz.length}${own(c) ? ` (budget ${own(c)})` : ''}`);
const over = chunks.filter((c) => own(c) && c.gz.length > own(c));
if (gz.length > BUDGET || total > TOTAL || over.length) {
  if (gz.length > BUDGET) console.error(`ui.js over budget by ${gz.length - BUDGET} bytes`);
  if (total > TOTAL) console.error(`ui.js and its chunks over budget by ${total - TOTAL} bytes`);
  for (const c of over) console.error(`ui/${c.name} over budget by ${c.gz.length - own(c)} bytes`);
  process.exit(1);
}
if (process.argv.includes('--check')) process.exit(0);

// TesserUI's icon, as src/tesserui/web_page.cpp inlines it.
const icon =
  "data:image/svg+xml,<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 16 16'><path d='M1 1h14v14H1zm4 4v6h6V5zl-4-4m14 0-4 4m0 6 4 4m-14 0 4-4' fill='none' stroke='%232f5bd3' stroke-width='2'/></svg>";

// For a CDN or GitHub Pages; a node generates its own page (WebUi).
writeFileSync(
  new URL('index.html', dist),
  '<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">' +
    `<title>TesserUI</title><link rel="icon" href="${icon}"></head><body><script type="module" src="launcher.js"></script></body></html>\n`,
);
writeFileSync(new URL('ui.js.gz', dist), gz);
for (const c of chunks) writeFileSync(new URL(`ui/${c.name}.gz`, dist), c.gz);

// FNV-1a 32, like TesserAPI's schema hash. ui.js names its chunks with their
// own hashes, so its ETag covers them.
let h = 0x811c9dc5;
for (const b of gz) h = Math.imul(h ^ b, 0x01000193) >>> 0;
const etag = h.toString(16).padStart(8, '0');

const array = (name, data) => {
  const bytes = [];
  for (let i = 0; i < data.length; i += 16) {
    bytes.push('    ' + [...data.subarray(i, i + 16)].map((b) => `0x${b.toString(16).padStart(2, '0')}`).join(', ') + ',');
  }
  return `alignas(4) inline constexpr uint8_t ${name}[] = {\n${bytes.join('\n')}\n};\n`;
};
const optional = (c) => OPTIONAL[c.name.replace(/-.*/, '')];
const guard = (c, text, otherwise = '') => {
  const m = optional(c);
  if (!m) return text;
  return `#if !defined(${m}) && !defined(CONFIG_${m})\n${text}${otherwise && `#else\n${otherwise}`}#endif\n`;
};
writeFileSync(
  header,
  `#pragma once
// Generated by web/scripts/bundle.mjs from the web build. Do not edit.
#include <stddef.h>
#include <stdint.h>
namespace tesserui {
namespace bundle {
inline constexpr char kVersion[] = "${version}";
inline constexpr char kEtag[] = "\\"${etag}\\"";
inline constexpr size_t kUiJsGzSize = ${gz.length};
${array('kUiJsGz', gz)}${chunks.map((c, i) => guard(c, array(`kChunk${i}`, c.gz))).join('')}
// The chunks ui.js loads from ui/, gzipped; one left out has no data.
struct Chunk {
    const char* name;
    const uint8_t* data;
    size_t size;
};
inline constexpr Chunk kChunks[] = {
${chunks.map((c, i) => guard(c, `    {"${c.name}", kChunk${i}, sizeof(kChunk${i})},\n`, `    {"${c.name}", nullptr, 0},\n`)).join('')}};
inline constexpr size_t kChunkCount = ${chunks.length};
}  // namespace bundle
}  // namespace tesserui
`,
);
console.log(`wrote dist/index.html, the gzipped copies and ${header.pathname.replace(/.*\/src\//, 'src/')} (etag ${etag})`);
